/**
 * Resolves curated or dynamically generated insights reliably with 0 network dependencies.
 */
export function getFallbackInsights(location: string, language: Language): { html: string; modelUsed: string } {
  const norm = location.toLowerCase();
  const archive = language === 'es' ? FALLBACK_INSIGHTS_ES : FALLBACK_INSIGHTS_EN;

  // 1. Direct or alias match
  for (const [alias, canonicalKey] of Object.entries(LOCATION_ALIASES)) {
    if (norm.includes(alias.toLowerCase())) {
      if (archive[canonicalKey]) {
        return {
          html: archive[canonicalKey],
          modelUsed: 'curated-archive',
        };
      }
    }
  }

  // 2. Substring match on archive keys
  for (const key of Object.keys(archive)) {
    if (norm.includes(key)) {
      return {
        html: archive[key],
        modelUsed: 'curated-archive',
      };
    }
  }

  // 3. Dynamic procedural generation for any searched location worldwide
  return {
    html: generateDynamicFallbackInsights(location.split(',')[0].trim(), language),
    modelUsed: 'curated-archive',
  };
}
